package ai.agent.entity.agent.task;

import java.util.List;

/**
 * <b>一次"经验归纳"的输出</b> —— 从这条任务问过什么、答过什么里读出来的规矩。
 *
 * <h2>为什么带一个 {@code usable} 而不是"空列表即不用"</h2>
 * 两种"没有规则"必须分得开：<b>读懂了、确实没什么可总结的</b>（例如这次确认问的是
 * "要不要顺带改一下注释"这种一次性的事），与<b>没读懂、样例不够</b>。
 * 前者不该写进技能，后者不该写进技能但值得留一条日志说"模型认为没有可归纳的内容"。
 * 合成一种之后，日志里那句"没写技能"就分不出是模型没给还是解析失败。
 *
 * <h2>为什么规则是"一句话一条"</h2>
 * 它们会被逐条写在技能的自补充段里（一条一行、以 {@code - } 开头）。写成一段连续的文字之后，
 * 下一次的模型读到的是"一大坨" —— 而这一件事的目的正是让"下一次相似的任务不必再问"，
 * 所以每条都要是能单独照着做的一句判断。
 *
 * @param usable 这次归纳有没有可用结论（false 时 {@code rules} 应为空）
 * @param rules 规则正文，一条一句（不带序号、不带 markdown 标记 —— 渲染时统一加 {@code - }）
 */
public record RuleSummary(boolean usable, List<String> rules) {
}
