package ai.agent.service.alert;

import java.util.List;

/**
 * 把"库里的信号"读成一份 {@link RuntimeSnapshot}（阶段四第 5 件）。
 *
 * <h2>为什么取数单独一个接口，而不是让 {@code AlertEvaluator} 直接查库</h2>
 * 判据是这个功能里最需要单独测的部分，而"用手造的 {@link RuntimeSnapshot} 测判据"
 * 与"用真库测取数"是两件<b>性质不同</b>的事：
 * <ul>
 *   <li>判据测试不该需要 H2、不该需要造 43 条评测数据 —— 它只该需要一份输入；</li>
 *   <li>取数测试不该顺带验证"连续空命中的阈值是 3" —— 那会让一条 SQL 的改动
 *       牵动一条业务规则的断言。</li>
 * </ul>
 * 分开之后，两边各自快、各自准，而且失败时指向的地方是明确的
 * （取数错了去查 SQL，判据错了去查枚举）。
 *
 * <h2>为什么它只读、且只读聚合值</h2>
 * 告警是<b>周期性跑</b>的东西，它会在服务活着的每一天被调用很多次。
 * 一个"把窗口内的行都读进内存再算"的实现，在本地几十条数据时完全没问题，
 * 上线几个月之后会变成"服务莫名其妙越来越慢" —— 而那时没有报错，只有慢。
 * 这与成本看板那条"聚合必须落在 SQL 里"是同一条分界。
 *
 * <p>⚠️ 本接口的实现<b>不许写任何东西</b>：一次"顺手建个索引"或"顺手补一行"
 * 会让告警评估变成一次有副作用的操作 —— 而它是被定时器调用的，
 * 那就变成了"半夜三点数据库被改了一下，没人知道是谁"。
 */
public interface AlertSnapshotQuery {

	/**
	 * 采集一次快照。
	 *
	 * @param days 时间窗（天）。含义与成本看板一致：1 = 只看今天。
	 * @return 一份不可变快照（见 {@link RuntimeSnapshot}）
	 */
	RuntimeSnapshot collect(int days);

	/**
	 * 灰度口径的观测结果。
	 *
	 * <p>单独一个方法而不是塞进 {@link #collect}：
	 * 它需要知道"当前开着的灰度是哪一版、重量多少"（配置侧）与
	 * "窗口内有多少份运行用了它"（数据侧），两处来源不同 ——
	 * 而把两处来源都写在一个方法里之后，"某一天这半边的 SQL 改了"
	 * 与"判据说比例偏了"就分不开了。
	 *
	 * @param days 与 {@link #collect} 同一个窗口，这样两条判据看到的是同一段事实
	 */
	AlertRule.CanarySplit canarySplit(int days);

	/**
	 * 窗口内"有 token、但匹配不到价格规则"的模型（显示名，可能含「未上报模型名」）。
	 *
	 * <p><b>为什么把它单独抽出来，而不是在取数实现里现算一遍</b>：
	 * 成本看板（{@code CostDashboardView}）算的是同一件事，而它算它的目的是
	 * 在页面上显示"哪些模型还没价"、把合计标成下界。
	 * 两处各算一遍的后果很具体：某次改动让其中一处把"未上报模型名"也算成有价，
	 * 于是<b>看板说金额是完整的、告警说有一半没算</b> —— 两句话互相矛盾，
	 * 而看的人只会信自己先打开的那一个。
	 *
	 * <p>抽出来之后，判据与页面读的是同一个方法。
	 * ⚠️ 它与 {@code CostDashboardView} 的 <b>UI 显示名</b>共享
	 * （「未上报模型名」这种写法只该有一处），所以常量也定义在这条链路上。
	 */
	List<String> unpricedModels(int days);

	/**
	 * 判据目录要用的窗口说明（不做任何查询）。
	 *
	 * <p>它单独存在是为了让"只想知道有哪几条判据"的请求
	 * （{@code GET /api/alerts/rules}）<b>一次库都不查</b> —— 那个端点是给人和给
	 * 监控系统看的说明书，它不该因为数据库慢而变慢。
	 */
	List<String> catalogNotes();

}
