package ai.agent.service.agent.approval;

/**
 * 一条审批记录的状态。
 *
 * <h2>为什么 {@code TIMED_OUT} 与 {@code DENIED} 必须分开</h2>
 * 两者对<b>后续动作</b>是同一个结果（这次调用不执行），所以很容易被合并成一个"否决"。
 * 但它们要通知的是<b>完全不同的人</b>：
 * <ul>
 *   <li>{@code DENIED} —— 有人看了、并做出了业务判断。要去问的是"他为什么不同意"；</li>
 *   <li>{@code TIMED_OUT} —— <b>没有人做任何判断</b>。要去修的是流程与值班：
 *       审批通知发到哪了、为什么没人看到、超时设得合不合理。</li>
 * </ul>
 * 合并之后，一个"审批流压根没接上"的系统会表现得像"业务上一直不同意"，
 * 而这两个问题的排查方向没有一寸重叠。
 *
 * <p>同一个理由也解释了为什么 {@code EXPIRED} 单独存在：它表示
 * "进程重启后这条待批已经无效"—— 那是<b>我们自己的生命周期</b>问题，
 * 与人事、业务都无关。
 */
public enum ApprovalStatus {

	/** 已登记，还没人处理。 */
	PENDING,

	/** 人工批准。 */
	APPROVED,

	/** 人工拒绝。 */
	DENIED,

	/** 在配置的时限内没有人处理 —— <b>不是"人拒绝了"</b>。 */
	TIMED_OUT,

	/**
	 * 因为进程重启/运行已结束而失效。
	 *
	 * <p>它拦的是一个很容易被忽略的漏洞：内存库里的"待批"会随重启消失，
	 * 但落库的记录还在。若不主动作废，界面会一直显示一条<b>永远点不动的</b>待批，
	 * 而运行本身早已结束。
	 */
	EXPIRED;

	/** 是否已经有人（或超时机制）给出结论。 */
	public boolean decided() {
		return this != PENDING;
	}

}
