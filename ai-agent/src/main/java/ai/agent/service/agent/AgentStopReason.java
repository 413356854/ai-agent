package ai.agent.service.agent;

/**
 * 循环为什么停下来。
 *
 * <p>做成枚举而不是"结束时看某个布尔值"：<b>停下来这件事本身就是结论</b>。
 * 用户在页面上问"为什么没答出来"，答案必须是"超出步数"还是"模型说完了"
 * 还是"被限流"，而不是笼统的"失败了"。
 *
 * <p>它同时也是成本控制的证据：{@code BUDGET_TOKENS} 说明这次任务花满了额度，
 * 下一次要调大；{@code DUPLICATE_ACTION} 说明模型在原地打转，
 * 要改的是工具描述或提示词，而不是额度。
 */
public enum AgentStopReason {

	/** 模型给出了最终文字回答（正常结束）。 */
	ANSWERED,

	/** 工具往返轮数达到上限。 */
	MAX_STEPS,

	/**
	 * 累计 token 达到上限。
	 *
	 * <p>注意它是在<b>下一次模型调用之前</b>判定的：这样可以避免"已经超了还再调一次模型"
	 * —— 那是纯浪费，因为请求本身可能已经被上游拒绝。
	 */
	MAX_TOKENS,

	/** 整个任务的墙上时间达到上限。 */
	MAX_DURATION,

	/**
	 * 同一个工具 + 同一份参数重复了太多次。
	 *
	 * <p><b>与 {@link #MAX_STEPS} 必须分开</b>：两者看起来都是"步数用完了"，
	 * 但要采取的措施完全相反 —— 前者是"任务复杂，额度不够"，后者是"模型卡住了"。
	 */
	DUPLICATE_ACTION,

	/** 模型既没给文字也没给工具调用（空响应）—— 上游异常，不是模型的"想法"。 */
	EMPTY_RESPONSE,

	/**
	 * <b>暂停等人确认</b>（HITL）：模型要求执行一次需要审批的写操作，而人还没表态。
	 *
	 * <h2>为什么它是独立的停因，而不是"失败"或"被上限拦下"</h2>
	 * 路线文档阶段三的验收里点名要能讲清「<b>什么时候让人确认</b>」——
	 * 而"停在这里等人"如果被并进 {@link #MAX_STEPS} 或 {@code MODEL_ERROR}，
	 * 那个问题就永远答不出来：报告里会显示"任务因为步数用完而停止"，
	 * 而真相是"它在等一个人点按钮"。
	 *
	 * <p>它同时决定了<b>续跑的语义</b>：带着这个停因结束的运行会在库里留下
	 * {@code status=WAITING_APPROVAL}，而恢复流程认得它 ——
	 * 拿到人的决定之后，从同一条检查点<b>接着跑</b>（不是从头重跑，
	 * 那会把暂停前已经执行过的只读工具再查一遍）。
	 *
	 * <p>与 {@link #DUPLICATE_ACTION} 那条理由完全同构：
	 * <b>看起来都像"没跑完"，但要采取的动作完全相反</b>
	 * （一个是"改提示词/工具描述"，一个是"去找人点按钮"）。
	 */
	WAITING_FOR_APPROVAL,

	/** 调模型时抛出异常（网络、鉴权、限流）。 */
	MODEL_ERROR

}
