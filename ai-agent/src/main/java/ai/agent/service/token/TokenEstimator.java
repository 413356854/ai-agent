package ai.agent.service.token;

/**
 * Token 数量估算器（学习点 2 的"怎么算"部分）。
 *
 * <p><b>为什么需要"估算"而不是"精确计算"</b>：token 数由<b>分词器</b>决定，
 * 而分词器是模型自带的 —— 想算得 100% 准，就必须把那个模型的分词器（词表文件）
 * 拿到本地跑。这条路有个死结：
 * <ul>
 *   <li>多数供应商（含 DeepSeek）<b>不公开发布分词器</b>，只提供
 *       "把文本发给我、我告诉你用了多少 token"的接口；</li>
 *   <li>就算拿到了词表，那也是<b>发请求之后</b>才知道的 —— 而预算校验的价值
 *       恰恰在于"<b>发之前</b>就知道"（发之前拒绝 = 0 成本，发之后报错 = 已经花了往返的钱）。</li>
 * </ul>
 * 所以工程上的正解是：<b>用可离线计算的估算 + 留足安全边际</b>，
 * 再用真实 usage 定期校准。
 *
 * <p>拆成接口是为了让"算法可替换"：将来换成真分词器（或某个供应商自己公布的
 * tokenizer），只要实现这个接口，预算守卫与业务代码一行都不用改。
 */
public interface TokenEstimator {

	/**
	 * 估算一段文本的 token 数。
	 *
	 * @param text 待估算文本，允许为 {@code null}（按 0 处理）
	 * @return 估算的 token 数，永不为负
	 */
	int estimate(String text);

	/**
	 * 估算一条消息的 token 数：正文 + <b>消息包装开销</b>。
	 *
	 * <p>为什么要单独有这个重载：对话协议里每条消息都要包一层角色结构
	 * （形如 {@code <|im_start|>user … <|im_end|>}），这部分不来自正文却要计费、占窗口。
	 * 只算正文会在"很多条短消息"的场景下系统性低估 —— 而系统提示词 + 20 条历史消息
	 * 恰好就是这种场景。
	 */
	int estimateMessage(String text);

	/**
	 * 估算整个请求的固定开销（回复引导符等），与消息条数无关。
	 */
	int requestOverhead();

}
