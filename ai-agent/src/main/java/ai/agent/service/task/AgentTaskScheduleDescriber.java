package ai.agent.service.task;

import java.time.Instant;
import java.time.ZoneId;

/**
 * <b>把定时任务的「描述模板」解析成"当下这条任务的描述"</b> —— 应用管理区 · 定时任务。
 *
 * <h2>为什么需要它</h2>
 * 定时规则里存的那句话是**周期性**的："把昨天的失败运行汇总成一份晨报"
 * 里那个"昨天"在规则里是相对的，而它派出去的那条任务是一条**一次性**的活 ——
 * 执行者（Agent）看不到"这是一条每月的规则"，它只看到那句描述。
 * 于是"昨天"到底指哪一天，必须在**派活的那一刻**定下来。
 *
 * <p>它同时是"每条任务描述都一模一样"这件事的解药：没有这一步，
 * 一条每天触发的规则会派出一串描述逐字相同的任务，
 * 而"昨天"这个词在每一条里其实指的是不同的日子。
 *
 * <h2>为什么要过模型，而不是拼一串日期进去</h2>
 * 规则里的时间说法没有固定语法：可能是"昨天"、"上个月"、"月初到现在"、
 * "本季度最后一次"、"上周五"。用占位符（{@code {yesterday}}）能覆盖的只是用户肯按约定写的那部分 ——
 * 而人写规则时不会照着模板写。交给模型是让"人怎么写都认"这件事成立的那条路。
 * 代价说清：**每次触发多一次模型调用**，而它也因此可能失败（见下面那条）。
 *
 * <h2>★ 失败时的处置：这一次不派活</h2>
 * 拿不到解析结果时<b>不派活</b>（{@link #resolve} 抛出，调用方接住、记一行 WARN，
 * 这条规则留到下一个周期重试）。理由：这一条链路上"描述"就是任务本身 ——
 * 拿模板原文派出去会得到一条含"昨天"的任务，而 Agent 会照它去猜一个日子，
 * 猜错的表现是**干错了一件事**（写错文件、汇总错日期），不是晚一天。
 * 这与"宁可晚，不可错"是同一条判断：定时派活的价值在于准时，
 * 而它派出去的那件事的价值在于做对。
 *
 * <h2>两条触发路径共用同一份解析</h2>
 * 到点触发（{@code AgentTaskScheduleRunner}）与界面上的「现在跑一次」
 * （{@code DefaultAgentTaskScheduleService#trigger}）都走 {@link #resolve} ——
 * 否则"手工试跑看到的那句话"与"真跑出来的那句话"会不是同一句，
 * 而手工试跑的用途恰恰就是"先确认一次再启用"。
 */
public interface AgentTaskScheduleDescriber {

	/**
	 * 解析一句描述模板。
	 *
	 * @param scheduleId 哪条规则（只用于日志与报错里定位）
	 * @param template 规则里存的那句描述（可能带周期说法）
	 * @param at 这次触发对应的时刻（<b>不是</b>"现在" —— 见下面那条）
	 * @param zone 用它把 {@code at} 说成人话（"现在几点、星期几"），也是"哪一天"的判据
	 * @return 解析结果；<b>模板里没有时间说法时原样返回</b>（{@link Resolved#changed()} 为 false）
	 * @throws TaskScheduleResolveException 模型没跑成 / 输出不可用 —— 调用方必须<b>不派活</b>
	 */
	Resolved resolve(Long scheduleId, String template, Instant at, ZoneId zone);

	/**
	 * 一次解析的结果。
	 *
	 * @param description 要写进那条任务的那一句（模板里没有时间说法时就是模板原文）
	 * @param changed 与模板相比有没有改动。它的用途只有一个：日志里说清
	 *        "这一次是模型真改了"还是"它原样返回了" —— 后者在排查
	 *        "为什么派出来的任务还写着昨天"时是第一个要看的读数
	 *        （它说明<b>解析跑了、但没认出来</b>，而不是"解析压根没跑"）
	 */
	record Resolved(String description, boolean changed) {
	}

}
