package ai.agent.service.review;

import java.time.Duration;
import java.util.List;

/**
 * 审查工单的存储契约 —— <b>本项目的"外部系统"替身</b>。
 *
 * <h2>为什么需要一个"外部系统"的替身，而不是直接写文件</h2>
 * 写操作这件事要能被验证，必须有一个地方能回答三个问题：
 * <ol>
 *   <li><b>它到底写了没有</b>（"审批被拒绝"与"审批通过了但写失败"必须分得开）；</li>
 *   <li><b>写了几次</b>（这正是路线文档面试追问里的「工具调用重试会不会产生重复副作用」）；</li>
 *   <li><b>谁批的</b>（审计闭环）。</li>
 * </ol>
 * 一个只有"写文件"的工具，前两个问题在测试里都很难断言（要读文件、要数行数）。
 * 有接口之后，测试可以注入一个可数的实现，而"真的写文件"那部分由另一个实现负责 ——
 * <b>两者各自被测一次，而不是混在一起互相干扰。</b>
 *
 * <h2>幂等窗口为什么是存储层的事，而不是工具层的事</h2>
 * "同一个标题不要建两条工单"这条规则如果写在工具里，那么任何<b>另一条</b>通向存储的路径
 * （将来的 MCP 直连、批处理导入）都会绕过它。
 * 幂等性是<b>存储的性质</b>，不是某个调用方的礼貌 —— 放在这一层，"重复"就无处可逃。
 *
 * @see FileTicketStore
 */
public interface TicketStore {

	/**
	 * 建一条工单。
	 *
	 * <p><b>幂等语义</b>：如果窗口内已经有一条"同标题 + 同级别"的工单，
	 * 返回<b>那一条</b>并把 {@code deduplicated} 置为 true，而不是再建一条。
	 *
	 * <p>这一点很重要，而且它是 HITL 能做得"舒服"的前提：
	 * 模型重复调用是被鼓励去避免的（回填里明确说了不要重提），
	 * 但<b>万一它还是重提了</b>——而人又批了——系统不该因此多出一条垃圾工单。
	 * 换句话说：<b>闸门是第一道防线，存储的幂等性是第二道</b>，
	 * 两道都在，"重复副作用"这个风险才真正被关掉。
	 */
	ReviewTicket create(String title, String detail, ReviewSeverity severity, String createdBy, String approvalId);

	/** 全部工单（按创建时间，新的在后）。 */
	List<ReviewTicket> all();

	/** 现有工单条数。 */
	int count();

	/** 幂等窗口。测试要能把它调小以便快速验证。 */
	Duration deduplicationWindow();

}
