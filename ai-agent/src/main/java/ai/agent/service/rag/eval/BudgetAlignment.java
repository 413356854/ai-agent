package ai.agent.service.rag.eval;

/**
 * 固定 token 预算下的召回 —— <b>等成本对照</b>。
 *
 * <h2>为什么按名次的指标还不够，必须再加这一套</h2>
 * 原始对照（500 字硬切 vs 结构分块）里有两处量纲没对齐，而它们都会让
 * "结构分块 Recall 更低"这个观察变得无法归因：
 * <ol>
 *   <li><b>块大小不同</b>（实测 234.8 vs 200.9 token）。判定标准是
 *       "检索到的块有没有覆盖答案所在章节"，<b>块越大越容易碰到答案</b>；</li>
 *   <li><b>检索预算相同但成本不同</b>。两边都取前 10 条，可大块那组
 *       取回来的 token 就是更多 —— 也就是说它<b>花了更多的钱</b>。
 *       "花更多钱换来更高召回"不构成"策略更好"。</li>
 * </ol>
 * 第 ① 条靠"把块大小对齐"解决（见 {@code RagAlignmentService}），
 * 第 ② 条则必须<b>把成本本身当成自变量</b>：同一个 token 预算下，
 * 谁能在预算内把答案找回来，谁才真的更划算。
 *
 * <h2>预算怎么装</h2>
 * 从名次 1 开始累加块大小，装到"下一个块会超预算"为止。
 * 第一条<b>无条件放行</b>：现实中遇到一个略超预算的块，会把它塞进去，
 * 而不是因为单个块太大就一条都不给 —— 样本要贴近真实行为，
 * 否则会量出一个在真实系统里不存在的行为。
 *
 * <p>这也让本指标天然体现"块越小、装进来的条数越多"这个权衡：
 * 相同预算下，小块能装更多条，但每条的信息量更少。
 * 到底哪个赢，只能靠数字说话 —— 这正是本记录类存在的理由。
 *
 * @param budget        预算档位（token）。文档里一律用 {@code 全部候选 token ≤ 预算} 的口径
 * @param recall        预算内的召回率（标准答案所在章节有没有出现在装进来的块里）
 * @param mrr           预算内第一个正确答案名次的倒数均值
 * @param avgTokensUsed 平均实际用掉的 token（≤ 预算；差得多说明块太大、装不满）
 * @param avgHitCount   平均装进来几条（与上一条一起看：预算没装满，是"块太大装不下"的直接证据）
 */
public record BudgetAlignment(int budget, double recall, double mrr, double avgTokensUsed, double avgHitCount) {
}
