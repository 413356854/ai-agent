package ai.agent.service.rag.kb;

/**
 * 文档索引流水线（上传 → 解析 → 分块 → 向量化 → 入库）。
 *
 * <h2>异步，但不引入 MQ</h2>
 * 一份文档的索引要跑几秒到几分钟（解析 + N 次 embedding 调用），不能占着上传的 HTTP 线程。
 * 本项目没有 MQ，用的是**进程内的有界线程池** —— 代价要写清楚：
 * 进程重启时队列里的任务会丢，所以启动时必须扫一遍库里还停在
 * {@code UPLOADED}/{@code PROCESSING} 的文档（见 {@link #recoverOnStartup()}），
 * 否则它们会永远停在那里，而"停着"与"正在跑"在界面上长得一样。
 */
public interface KbIndexingService {

	/**
	 * 把一份文档排进索引队列。
	 *
	 * <p>队列满时**不阻塞调用方**，而是把那份文档标成失败并写明原因：
	 * 一个卡住的上传接口（HTTP 线程上等队列）比一条明确的失败更难查
	 * —— 前者表现为"上传转圈"，没有错误、也没有结果。
	 */
	void submit(long documentId);

	/**
	 * 在当前事务**提交之后**再入队。
	 *
	 * <h2>为什么不能直接在事务里 submit</h2>
	 * 索引线程是另一个线程、另一条连接，它读不到还没提交的那一行 ——
	 * 实测（2026-10-17）：上传接口里的 {@code submit} 比提交早 0 毫秒级地跑起来，
	 * 索引线程读到 {@code null}，于是**静默跳过**（日志里只有一句"文档已经不在了"），
	 * 文档永远停在「已上传」。它看起来像"队列没动"，而队列其实是好的。
	 *
	 * <p>所以凡是"写一行 + 让另一个线程去处理这一行"的地方，都要走这个方法。
	 * 没有事务在跑时（比如启动清扫）它等同于 {@link #submit(long)}。
	 */
	void submitAfterCommit(long documentId);

	/**
	 * 启动清扫。
	 *
	 * <p>两种未完成状态的处理**刻意不同**：
	 * <ul>
	 *   <li>{@code UPLOADED}：重新入队。任务可以确定还没开始跑，重跑不会写重；</li>
	 *   <li>{@code PROCESSING}：标成失败，原因写"进程在索引过程中退出"。**不自动重跑** ——
	 *       一份被半途中断的文档如果后来悄悄补完，它与一份干净索引出来的文档在库里完全一样，
	 *       而"这次到底有没有被中断过"是排查检索结果时最想知道的事。</li>
	 * </ul>
	 */
	void recoverOnStartup();

}
