package ai.agent.agent.store;

/**
 * 一次 Agent 运行在库里的状态。
 *
 * <p><b>为什么 {@code RUNNING} 与 {@code INTERRUPTED} 必须分开</b>：
 * 它们看起来都像"没跑完"，但含义完全不同 ——
 * <ul>
 *   <li>{@code RUNNING}：进程还活着，正在跑。另一个实例不该去动它（那是抢别人的活）；</li>
 *   <li>{@code INTERRUPTED}：进程死了，留下的那一行。**只有它才该被恢复**。</li>
 * </ul>
 * 合并成一个状态，恢复逻辑就会分不清"正在跑"和"已经死了"，
 * 于是要么漏掉该恢复的，要么去抢正在跑的活（后者更糟：两个实例同时跑同一次任务，
 * 工具会被执行两遍）。
 */
public enum RunStatus {

	/** 正在跑（进程存活）。 */
	RUNNING,

	/** 正常给出答案结束。 */
	ANSWERED,

	/** 被某个上限拦下（步数/token/时长/重复动作）—— 这是**正常结束**的一种，不是故障。 */
	STOPPED,

	/** 失败结束（模型调用炸了、工具炸了）。 */
	FAILED,

	/**
	 * 被中断：进程在跑的过程中消失（被杀 / 崩溃 / 断电）。
	 *
	 * <p>这个状态**不是应用自己写进去的**，而是恢复逻辑在启动时"推断"出来的：
	 * 库里留着 {@code RUNNING} 的行，但当前进程里没有对应的运行 —— 于是它被标记为中断。
	 * 换句话说：{@code RUNNING} 是运行期的事实，{@code INTERRUPTED} 是**下一次启动时的结论**。
	 */
	INTERRUPTED,

	/**
	 * <b>停在等人确认</b>（HITL）：模型要求一次写操作，而人还没表态。
	 *
	 * <h2>为什么它必须与 RUNNING 分开 —— 分开它救的是一个很严重的 bug</h2>
	 * 两者都表示"没跑完"，但"下次启动时该怎么办"完全相反：
	 * <ul>
	 *   <li>{@code RUNNING} → 进程没了，这次的上下文只存在于检查点里，
	 *       所以要标记成中断、等人决定要不要恢复；</li>
	 *   <li>{@code WAITING_APPROVAL} → <b>它是正常活着的状态</b>：
	 *       任务停在一个人工闸门上等人点按钮。上下文完整、检查点完整。</li>
	 * </ul>
	 * 如果把待批写进 {@code RUNNING}，那么<b>下一次启动的"认领遗留运行"逻辑会把它
	 * 当成被中断的运行去自动恢复</b> —— 而"恢复"意味着重新问模型、重新提出那个写调用，
	 * 于是产生<b>第二条待批</b>。人在界面上看到两条一模一样的待批，
	 * 批了一条、另一条仍然挂着，而运行的状态谁也说不清。
	 *
	 * <p>换句话说：这个枚举值的作用是<b>让"等待恢复"的逻辑跳过等待审批的运行</b>——
	 * 它已经在正确的等待里了，不需要任何人去"救"它。
	 */
	WAITING_APPROVAL

}
