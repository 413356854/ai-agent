package ai.agent.agent;

/**
 * 循环为什么停下来。
 *
 * <p>做成枚举而不是"结束时看某个布尔值"：<b>停下来这件事本身就是结论</b>。
 * 用户在页面上问"为什么没答出来"，答案必须是"超出步数"还是"模型说完了"
 * 还是"被限流"，而不是笼统的"失败了"。
 *
 * <p>它同时也是成本控制的证据：{@code BUDGET_TOKENS} 说明这次任务花满了额度，
 * 下一次要调大；{@code DUPLICATE_ACTION} 说明模型在原地打转，
 * 要改的是工具描述或提示词，而不是额度。
 */
public enum AgentStopReason {

	/** 模型给出了最终文字回答（正常结束）。 */
	ANSWERED,

	/** 工具往返轮数达到上限。 */
	MAX_STEPS,

	/**
	 * 累计 token 达到上限。
	 *
	 * <p>注意它是在<b>下一次模型调用之前</b>判定的：这样可以避免"已经超了还再调一次模型"
	 * —— 那是纯浪费，因为请求本身可能已经被上游拒绝。
	 */
	MAX_TOKENS,

	/** 整个任务的墙上时间达到上限。 */
	MAX_DURATION,

	/**
	 * 同一个工具 + 同一份参数重复了太多次。
	 *
	 * <p><b>与 {@link #MAX_STEPS} 必须分开</b>：两者看起来都是"步数用完了"，
	 * 但要采取的措施完全相反 —— 前者是"任务复杂，额度不够"，后者是"模型卡住了"。
	 */
	DUPLICATE_ACTION,

	/** 模型既没给文字也没给工具调用（空响应）—— 上游异常，不是模型的"想法"。 */
	EMPTY_RESPONSE,

	/** 调模型时抛出异常（网络、鉴权、限流）。 */
	MODEL_ERROR

}
