package ai.agent.tool;

/**
 * 一次工具调用尝试走到了哪一步。
 *
 * <p>做成枚举而不是字符串常量：报告、自检断言、统计都靠它，
 * 而字符串一旦拼错就<b>静默变成"另一个类别"</b>（统计里少一项，没人会发现）。
 *
 * <p>顺序即"从外到内"的处理顺序 —— {@code ToolCallExecutor} 也是按这个顺序设门禁的。
 */
public enum ToolCallStage {

	/**
	 * 模型提出的工具名不在注册表里。
	 *
	 * <p><b>这是最该被单独统计的一类</b>：它百分百是模型的问题（或工具描述没写好），
	 * 而不是参数的问题。实测中最常见的成因是"工具名起得太像"——
	 * 模型把 {@code search_docs} 记成了 {@code doc_search}。
	 */
	UNKNOWN_TOOL,

	/**
	 * 参数不是合法 JSON，或字段类型与声明对不上（例如把数字写成字符串）。
	 *
	 * <p>与 {@link #VALIDATION_ERROR} 分开的理由：给模型的建议不同 ——
	 * 这一类要说"JSON 语法/类型"，那一类要说"哪个字段的值不合法"。
	 */
	PARSE_ERROR,

	/**
	 * JSON 合法，但过不了 JSR-380 约束（缺必填字段、数值越界、字符串太长）。
	 *
	 * <p>之所以值得单独一类：这一类是<b>最有可能被模型自己修好的</b>，
	 * 前提是回填里带上"哪个字段、错在哪、可用值是什么"。
	 */
	VALIDATION_ERROR,

	/**
	 * 参数合法、工具也开始执行了，但执行过程中抛出异常（实现 bug、依赖炸了、超时）。
	 *
	 * <p>与工具自己返回的 {@code Failure} 区分开：那种情况 stage 仍然是 {@link #OK}
	 * （工具正常完成了它的工作，只是工作上报告了一个否定结论）。
	 *
	 * <p><b>它是唯一会被计入熔断失败率的一类</b> —— 理由见
	 * {@link #REQUEST_REJECTED} 与 {@code CircuitBreaker} 的注释：
	 * 熔断要回答的是"工具/依赖还健康吗"，而模型把参数写错不是工具不健康。
	 */
	EXECUTION_ERROR,

	/**
	 * 被并发闸门或限流<b>主动拒绝</b>了（没让它执行）。
	 *
	 * <h2>为什么它必须是一个独立的 stage，而不是"另一种 EXECUTION_ERROR"</h2>
	 * 两者对模型要引导出<b>相反</b>的动作：
	 * <ul>
	 *   <li>{@code EXECUTION_ERROR}：工具/依赖坏了 → 换个参数、换个工具，或者别试了；</li>
	 *   <li>{@code REQUEST_REJECTED}：<b>只是这一会儿太挤</b> → 稍后用同样的参数重试<b>有意义</b>。</li>
	 * </ul>
	 * 合并成一类，模型在限流期间会开始换工具、换参数乱试 —— 而那些尝试同样会被拒，
	 * 于是它在一个"其实只要等一秒"的问题上浪费掉好几轮预算。
	 *
	 * <p>更关键的是它<b>绝不能被计入熔断失败率</b>：限流本身就是"我们在保护下游"，
	 * 如果把被拒的请求算成下游失败，就会推着熔断器去打开一个本来健康的工具的闸门 ——
	 * 于是保护措施自己制造了一次故障。
	 */
	REQUEST_REJECTED,

	/**
	 * 熔断器是打开状态，这次调用<b>没有真的发出去</b>。
	 *
	 * <p>与 {@link #REQUEST_REJECTED} 分开：那个是"太挤了，稍后可以重试"，
	 * 这个是"这把工具（或它依赖的下游）已经确定在坏了，别再试它"。
	 * 让模型分清这两件事，它才知道该等还是该换。
	 */
	CIRCUIT_OPEN,

	/** 工具正常执行完并返回了结果 —— <b>包括工具返回"没查到"这种情况</b>。 */
	OK;

	/**
	 * 这个 stage 该不该计入<b>熔断</b>的失败率。
	 *
	 * <p>判据只有一条：<b>失败是"工具/依赖"造成的，还是"模型/我们自己的保护措施"造成的。</b>
	 * 只有前者算失败。这不是洁癖 —— 算错方向会让熔断器做出与初衷相反的事：
	 * <ul>
	 *   <li>把 {@code VALIDATION_ERROR} 算失败：模型偶尔连写几个错参数，
	 *       就会把一个完全健康的工具熔断掉。<b>模型的错不该由工具的可用性来买单</b>；</li>
	 *   <li>把 {@code REQUEST_REJECTED} 算失败：限流期间被拒的请求会累积成"高失败率" →
	 *       熔断打开 → 于是既限流又熔断，保护措施自己制造了一次故障。</li>
	 * </ul>
	 *
	 * <p>这是本轮最值得单独记下来的一个判断：
	 * <b>"失败率"这个词听起来没有歧义，但它的分母和分子都要按"归因"来定，
	 * 而不是按"没成功"来定。</b>
	 */
	public boolean countsAsToolFailure() {
		return this == EXECUTION_ERROR;
	}

}
