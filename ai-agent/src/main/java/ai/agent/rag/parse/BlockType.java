package ai.agent.rag.parse;

/**
 * 解析后文本块的类型。
 *
 * <p><b>为什么解析结果不是"一个 String"，而是要分出块类型</b>：
 * 阶段二要做的第一件事是"别按固定字数硬切"，而"不硬切"的前提是
 * <b>知道哪些地方是天然的边界</b>。这些信息在原始文本里是存在的
 * （Markdown 的 {@code #}、HTML 的 {@code <h2>}、Word 的标题样式），
 * 但只要中途退化成 {@code List<String>} 就全丢了 —— 之后无论怎么切，
 * 都只能按长度猜，等于把结构信息白扔了。
 *
 * <p>所以解析层的输出刻意保留了类型：切分层据此决定"在哪里切、切完怎么加面包屑"。
 */
public enum BlockType {

	/**
	 * 标题。{@link ParsedBlock#level()} 表示层级（1 = 一级标题）。
	 *
	 * <p>它同时承担两个职责：<b>切分边界</b>（标题变化 = 主题变化，最可靠的切点）
	 * 和<b>上下文来源</b>（块被单独召回时，靠标题路径才知道自己属于哪一节）。
	 */
	HEADING,

	/** 正文段落。切分的基本单位 —— 一段话被拦腰截断是"硬切"最典型的伤害。 */
	PARAGRAPH,

	/** 列表项。列表内部通常语义耦合，切分时尽量不拆散同一个列表。 */
	LIST_ITEM,

	/**
	 * 表格。
	 *
	 * <p>单列出来是因为它<b>不可切</b>：一张表被切到两个块里，
	 * 两个块都只拿到半张表头，谁都用不了（本项目台账里大量结论都是表格形态，
	 * 这个类型会被真实用到）。切分层对它的策略是"整表尽量不拆"。
	 */
	TABLE,

	/** 代码块。同样不可切 —— 半段代码没有意义，而且缩进信息在跨块时会失真。 */
	CODE,

	/** 引用块。 */
	QUOTE,

	/** 兜底类型：解析器认识结构但没归入以上类别的内容。 */
	OTHER;

}
